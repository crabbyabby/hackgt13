from typing import Protocol

from backend.app.domain.models import ExtractionJob, SemanticNote


class NoteRepository(Protocol):
    async def save(self, note: SemanticNote) -> SemanticNote: ...
    async def find_by_id(self, note_id: str) -> SemanticNote | None: ...
    async def find_by_slug(self, slug: str) -> SemanticNote | None: ...


class JobRepository(Protocol):
    async def save(self, job: ExtractionJob) -> ExtractionJob: ...
    async def find_by_id(self, job_id: str) -> ExtractionJob | None: ...
